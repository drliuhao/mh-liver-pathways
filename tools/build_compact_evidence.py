"""Generate assets/compact-evidence-data.js from tools/compact_evidence_source.json.

Presentation data only. The concise lines restate numbers already present in the
site's verified source text; see tools/test_compact_evidence.py for the guard.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
src = json.loads((ROOT / 'tools/compact_evidence_source.json').read_text())
studies = {}
for pmid, s in src['studies'].items():
    # Only identity fields are published for studies; numbers reach an option only through 'options'.
    item = {'l': s.get('label'), 'd': s.get('design')}
    studies[pmid] = {k: v for k, v in item.items() if v}
options = {key: {'g': o['lead'][:40], 'rows': [{k: v for k, v in {'p': r['pmid'], 'r': r['result'], 'c': r.get('caution')}.items() if v} for r in o['rows']]}
           for key, o in src.get('options', {}).items() if o['rows']}
# Reviewed source-study evidence groups (HCC treatment references), linked explicitly to options.
matrix_cards = {c['id']: c for c in json.loads((ROOT / 'systemic/matrix.json').read_text())['cards']}
references = {}
for key, group_ids in src.get('reference_links', {}).items():
    groups = []
    for gid in group_ids:
        g = src['reference_groups'][gid]
        item = {'k': g['kind'], 'id': gid, 't': g['title'], 's': g.get('sub', ''), 'w': g['context'],
                'rows': [[r['trial'], r['pmids'], r['result'], r.get('arms', ''), r.get('caution', '')] for r in g['rows']]}
        if g['kind'] == 'systemic':
            card = matrix_cards[g['card']]
            item.update({'card': card['id'], 'pos': card['position'], 'l': card['limits']})
        groups.append(item)
    references[key] = groups
payload = {'version': src['version'], 'studies': studies, 'options': options, 'references': references}
(ROOT / 'assets/compact-evidence-data.js').write_text(
    '/* Generated by tools/build_compact_evidence.py from tools/compact_evidence_source.json. Presentation data only. */\n'
    'window.CompactEvidenceData=' + json.dumps(payload, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(f"{len(studies)} studies; {len(options)} options with {sum(len(o['rows']) for o in options.values())} option-tied results; "
      f"{len(references)} options linked to {sum(len(g) for g in references.values())} treatment-reference groups")
