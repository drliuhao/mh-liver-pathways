        g['title']=g['title'].replace('one row per','one entry per')
        for f in g['fields']:
            f['help']=f['help'].replace('one specimen row','one specimen entry')
            if f['type'] in ('number','integer') and f['id']!='labs.value':f.setdefault('min',0)
            if f['unit']=='%':f['max']=100
