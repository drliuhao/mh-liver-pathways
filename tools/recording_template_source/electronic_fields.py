    for f,label in [('preliminary','Preliminary / frozen result'),('final','Permanent pathology result')]:
        pick('staging_specimens.'+f,label,'negative_for_malignancy;positive_for_malignancy;indeterminate;inadequate;pending;not_performed;other')
