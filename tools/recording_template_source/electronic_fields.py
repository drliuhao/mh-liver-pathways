"""Typed electronic fields. Documentation choices do not set clinical criteria."""
def configure(modules):
    def update(fid, label=None, dtype=None, unit=None, choices=None, help=None, **extra):
        g,key=fid.split('.')
        field=next(f for f in modules[g]['fields'] if f['id']==fid)
        for k,v in dict(label=label,type=dtype,unit=unit,choices=choices,help=help,**extra).items():
            if v is not None:field[k]=v
        return field
    def add(g,key,label,dtype='text',unit='',choices=None,help='',**extra):
        modules[g]['fields'].append(dict(id=g+'.'+key,label=label,type=dtype,unit=unit,choices=choices or [],help=help,**extra))
    def pick(fid,label,choices,help=''):
        update(fid,label,'choice','',choices.split(';'),help)
    def number(fid,label,unit='',integer=False,help=''):
        update(fid,label,'integer' if integer else 'number',unit,[],help,min=0)
    def date(fid,label):update(fid,label,'date','',[],'')
    def extra(g,key,label,choices):add(g,key,label,'choice',choices=choices.split(';'))
