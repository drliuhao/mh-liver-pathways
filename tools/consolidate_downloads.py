"""Archive legacy authored downloads and consolidate serving links.

This operation never edits an Office/PDF binary. Archive copies are hash checked
before a legacy serving file may be removed. Run --archive, then --links, then
--retire; the clinical-revision applier is a separate explicit step.
"""
from pathlib import Path
import argparse, hashlib, json, shutil
import current_downloads as D

ROOT=D.ROOT
ARCHIVE=ROOT.parent/'Artifact_Sync_2026-11-02/Archived_Web_Downloads'
REV='2026-11-02-zzzzzzzz-download-consolidation'
def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def write(path,value):path.write_text(json.dumps(value,ensure_ascii=False,indent=2)+'\n')

def archive():
    source=json.loads((ROOT/'tools/artifact_sync/legacy_target_to_current_mapping.json').read_text())
    entries=source['word']+source['pdf'];assert len(source['word'])==45 and len(source['pdf'])==9
    records=[]
    for row in entries:
        rel=row['old_path'];old=ROOT/rel;copy=ARCHIVE/rel
        target='hilar/' if rel=='lrt/pcca-decision-chart.pdf' else row['current_target']
        assert (ROOT/target).exists(),target
        if old.exists():
            original=sha(old);copy.parent.mkdir(parents=True,exist_ok=True)
            if copy.exists():assert sha(copy)==original,copy
            else:shutil.copy2(old,copy)
            assert sha(copy)==original and sha(old)==original,rel
        else:
            assert D.MANIFEST.exists() and copy.exists(),rel
            original=next(x['sha256'] for x in D.rows() if x['old_path']==rel)
            assert sha(copy)==original,rel
        records.append({'old_path':rel,'current_target':target,'sha256':original,
                        'bytes':copy.stat().st_size,'archive_path':rel})
    manifest={'edition':'V18','archive_directory':'Artifact_Sync_2026-11-02/Archived_Web_Downloads',
      'purpose':'Unchanged retired author-created website downloads; publication PDFs are excluded.',
      'word_files':45,'authored_pdf_files':9,'files':records}
    ARCHIVE.mkdir(parents=True,exist_ok=True)
    write(ARCHIVE/'hash_manifest.json',manifest);write(D.MANIFEST,manifest)
    print('Archived and hash-verified 45 Word + 9 authored PDF files unchanged.')

def links():
    content_path=ROOT/'transplant/assets/content.json';old=json.loads(content_path.read_text());new=D.rewrite_data(old)
    edits=[]
    def diff(a,b,path=()):
        if isinstance(a,dict):
            for k in a:diff(a[k],b[k],path+(k,))
        elif isinstance(a,list):
            for i in range(len(a)):diff(a[i],b[i],path+(i,))
        elif a!=b:edits.append({'op':'replace_value','path':list(path),'old':a,'new':b})
    diff(old,new)
    rev={'id':REV,'requested_by':'Hao Liu: synchronize current website downloads and retire superseded authored copies',
      'status':'Serving URLs and document metadata only; clinical claims, criteria and rules unchanged.',
      'sources':[],'edits':edits,'files':[]}
    revision_path=ROOT/'tools/clinical_revisions'/f'{REV}.json'
    if revision_path.exists():
        # The existing release record also contains separately applied metadata
        # and generator changes. Never erase it on a repeated link-only pass.
        recorded=json.loads(revision_path.read_text())
        assert not edits or recorded['edits'][:len(edits)]==edits,'Conflicting consolidation revision'
    else:write(revision_path,rev)
    changed=[]
    # Static fallback links and generator input metadata. Protected clinical
    # payloads are updated only through the recorded revision and its applier.
    files=list(ROOT.rglob('*.html'))+[ROOT/'tools/decision_assistant_source/high_risk_data.json']
    for f in files:
        if any(x in f.parts for x in ('.git','node_modules')):continue
        text=f.read_text();after=D.rewrite_text(text)
        after=after.replace('Full V7 protocol PDF','Current high-risk pathway · Word').replace('Download the V7 discussion document (.docx)','Current high-risk pathway · Word').replace('Cross-tumor systemic matrix DOCX','Current cross-tumor systemic matrix')
        # The embedded clinical payload is regenerated by the exact revision.
        if after!=text:f.write_text(after);changed.append(str(f.relative_to(ROOT)))
    f=ROOT/'transplant/high-risk/integrated-protocols.json';data=json.loads(f.read_text())
    for slug,entry in data['pathways'].items():
        entry['documents']=[{'url':D.BASE+D.high_risk_document(slug),'label':'Current high-risk pathway · Word','format':'docx'}]
    write(f,data);changed.append(str(f.relative_to(ROOT)))
    # Keep the source review immutable; this inventory describes current serving
    # destinations and deliberately does not pin hashes while V18 is authored.
    write(ROOT/'transplant/high-risk/authored-documents.json',[
      {'path':D.high_risk_document(slug),'kind':'Current V18 author-created pathway; not a journal article'}
      for slug in data['pathways']])
    catalog_path=ROOT/'evidence-libraries/catalog.json';catalog=json.loads(catalog_path.read_text())
    manifest=json.loads((ROOT/'assets/documents.json').read_text())['tumors']
    for lib in catalog['libraries']:
        lib['ppt_filename']='Evidence_Summaries_v18.pptx'
        if not lib['local_folder'].startswith('V18_consistent_release_2026-11-02/'):
            lib['local_folder']='V18_consistent_release_2026-11-02/Evidence_Libraries/'+lib['local_folder']
        key=lib['key']
        if key=='liver_directed_matrix':lib['document']='lrt/'
        elif key=='systemic_matrix':lib['document']='systemic/'
        elif key=='meeting_allocation':lib['document']='transplant/high-risk/#readiness'
        else:
            prefix=next((x for x in ['roadmap_','standard_','high_risk_','meeting_'] if key.startswith(x)),None)
            slug='hcc' if key=='hcc_afp_b1_1' else key.removeprefix(prefix or '')
            slot={'roadmap_':'roadmap_info','standard_':'standard_info','high_risk_':'highrisk_info','meeting_':'decision'}.get(prefix,'decision')
            lib['document']='documents/'+slug+'/'+manifest[slug]['files'][slot]
    write(catalog_path,catalog)
    exp=ROOT/'transplant/export-manifest.json';obj=json.loads(exp.read_text())
    obj['documents']=[{'path':f,'edition':'V18'} for f in D.canonical_files()]
    obj['editorial_documents']=[{'path':f,'edition':'V18'} for f in D.canonical_files()]
    obj['high_risk_protocol_pdfs']=0
    obj['document_edition']='V18';obj['document_link_consolidation']='2026-11-02; 54 unchanged legacy authored binaries archived outside the served repository'
    write(exp,obj)
    pub=ROOT/'transplant/high-risk/publication-manifest.json';obj=json.loads(pub.read_text());obj['authored_protocol_pdfs']=0;obj['document_edition']='V18';write(pub,obj)
    print(f'Prepared {len(edits)} exact protected URL edits and updated {len(changed)} serving fallback/source files plus metadata.')

def retire():
    for row in D.rows():
        target=ROOT/row['old_path'];copy=ARCHIVE/row['archive_path']
        assert copy.is_file() and sha(copy)==row['sha256'],copy
        if target.exists():assert sha(target)==row['sha256'],target;target.unlink()
    assert len(list((ROOT/'documents').glob('*/*.docx')))==65
    print('Retired all 54 hash-verified legacy binaries; 65 canonical Word downloads retained.')

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('action',choices=['--archive','--links','--retire'])
    # Deliberately use explicit phases instead of importing this module for side effects.
    import sys
    action=sys.argv[1] if len(sys.argv)==2 else ''
    if action not in ('--archive','--links','--retire'):raise SystemExit('usage: consolidate_downloads.py --archive|--links|--retire')
    {'--archive':archive,'--links':links,'--retire':retire}[action]()
